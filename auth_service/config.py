"""Trusted server-side configuration.

All hash parameters that the service will *honor* live here.  Parameters
stored in the database are only accepted if they fall inside the ranges
defined by this config, so a tampered record can never make the server
allocate huge amounts of memory or run for an unbounded time.
"""

import json


class ConfigError(Exception):
    pass


def default_config_dict():
    return {
        # PBKDF2-HMAC-SHA256 (legacy credentials)
        "pbkdf2_iterations": 210000,
        "pbkdf2_min_iterations": 100000,
        "pbkdf2_max_iterations": 2000000,
        # scrypt (current credentials)
        "scrypt_n": 16384,
        "scrypt_r": 8,
        "scrypt_p": 1,
        "scrypt_min_n": 1024,
        "scrypt_max_n": 131072,
        "scrypt_max_r": 16,
        "scrypt_max_p": 8,
        "scrypt_maxmem": 268435456,  # 256 MiB hard cap passed to hashlib.scrypt
        # shared
        "dklen": 32,
        "salt_len": 16,
        "password_max_bytes": 256,
        "username_max_bytes": 128,
        "session_ttl_seconds": 86400,
        "body_max_bytes": 8192,
        # local admin token for /admin/reset (generated by `cli init`)
        "admin_token": "",
        # test-only synchronization / crash hooks (never enable in production)
        "enable_test_hooks": False,
        "hook_dir": "",
    }


_INT_KEYS = {
    "pbkdf2_iterations", "pbkdf2_min_iterations", "pbkdf2_max_iterations",
    "scrypt_n", "scrypt_r", "scrypt_p", "scrypt_min_n", "scrypt_max_n",
    "scrypt_max_r", "scrypt_max_p", "scrypt_maxmem", "dklen", "salt_len",
    "password_max_bytes", "username_max_bytes", "session_ttl_seconds",
    "body_max_bytes",
}


def _is_int(x):
    return isinstance(x, int) and not isinstance(x, bool)


class Config:
    """Flat, validated, read-only view over the config values."""

    def __init__(self, values):
        self._values = dict(values)

    def __getattr__(self, name):
        try:
            return self._values[name]
        except KeyError:
            raise AttributeError(name)

    def as_dict(self):
        return dict(self._values)


def validate(d):
    for key in _INT_KEYS:
        if not _is_int(d[key]) or d[key] <= 0:
            raise ConfigError(f"{key} must be a positive integer")
    if not isinstance(d["admin_token"], str):
        raise ConfigError("admin_token must be a string")
    if not isinstance(d["enable_test_hooks"], bool):
        raise ConfigError("enable_test_hooks must be a boolean")
    if not isinstance(d["hook_dir"], str):
        raise ConfigError("hook_dir must be a string")
    if not d["admin_token"]:
        raise ConfigError("admin_token must not be empty")
    if not (d["pbkdf2_min_iterations"] <= d["pbkdf2_iterations"]
            <= d["pbkdf2_max_iterations"]):
        raise ConfigError("pbkdf2 iterations must satisfy min <= current <= max")
    n = d["scrypt_n"]
    if n & (n - 1):
        raise ConfigError("scrypt_n must be a power of two")
    if not (d["scrypt_min_n"] <= n <= d["scrypt_max_n"]):
        raise ConfigError("scrypt_n outside [scrypt_min_n, scrypt_max_n]")
    if d["scrypt_min_n"] & (d["scrypt_min_n"] - 1) or d["scrypt_max_n"] & (d["scrypt_max_n"] - 1):
        raise ConfigError("scrypt min/max n must be powers of two")
    if 128 * n * d["scrypt_r"] * d["scrypt_p"] > d["scrypt_maxmem"]:
        raise ConfigError("configured scrypt parameters exceed scrypt_maxmem")
    if d["enable_test_hooks"] and not d["hook_dir"]:
        raise ConfigError("hook_dir is required when enable_test_hooks is true")


def load_config(path):
    d = default_config_dict()
    with open(path, "r", encoding="utf-8") as f:
        try:
            user = json.load(f)
        except json.JSONDecodeError as e:
            raise ConfigError(f"invalid config JSON: {e}")
    if not isinstance(user, dict):
        raise ConfigError("config must be a JSON object")
    unknown = sorted(set(user) - set(d))
    if unknown:
        raise ConfigError(f"unknown config keys: {unknown}")
    d.update(user)
    validate(d)
    return Config(d)
